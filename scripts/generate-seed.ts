/**
 * Generates supabase/seed.sql from the demo fixtures in src/mocks, so the database demo matches the
 * in-memory demo exactly. Run: npm run db:seed:generate
 */
import fs from "node:fs";
import path from "node:path";
import { AGENTS, ORDERS } from "../src/mocks/fleet";
import { AUDIT_EVENTS, REPORTS } from "../src/mocks/reports";

const q = (v: string | number | null | undefined) =>
  v === null || v === undefined ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const j = (v: unknown) => `$json$${JSON.stringify(v)}$json$::jsonb`;

const lines: string[] = [
  "-- GENERATED by scripts/generate-seed.ts from src/mocks — do not edit by hand.",
  "-- Demo data for AwaazOps (fictional agents, customers and orders, Bengaluru, 6 Nov 2026).",
  "",
  "begin;",
  "",
];

for (const a of AGENTS) {
  lines.push(`insert into public.agents (id, name, phone_masked, hub, preferred_language) values (${[a.id, a.name, a.phoneMasked, a.hub, a.preferredLanguage].map(q).join(", ")});`);
}
lines.push("");

for (const o of ORDERS) {
  lines.push(
    `insert into public.orders (id, customer_name, customer_phone_masked, address_line, locality, city, pincode, status, priority, assigned_agent_id, slot_start, slot_end, instructions, updated_at) values (${[
      o.id, o.customerName, o.customerPhoneMasked, o.addressLine, o.locality, o.city, o.pincode, o.status, o.priority,
      o.assignedAgentId, o.slotStart, o.slotEnd, o.instructions, o.updatedAt,
    ].map(q).join(", ")});`,
  );
}
lines.push("");

for (const d of REPORTS) {
  const stored = {
    report: d.report,
    transcript: d.transcript,
    extraction: d.extraction,
    validation: d.validation,
    actionId: d.action?.id ?? null,
    priority: d.priority,
    confirmationPrompt: d.confirmationPrompt,
  };
  lines.push(`select public.save_report(${j(stored)});`);
}
lines.push("");

for (const d of REPORTS) {
  const a = d.action;
  if (!a) continue;
  lines.push(
    `insert into public.operational_actions (id, report_id, order_id, type, payload, status, confirmed_by, confirmed_at, executed_at) values (${q(a.id)}, ${q(a.reportId)}, ${q(a.orderId)}, ${q(a.type)}, ${j(a.payload)}, ${q(a.status)}, ${q(a.confirmedBy)}, ${q(a.confirmedAt)}, ${q(a.executedAt)});`,
  );
}
lines.push("");

// Oldest first, so the identity sequence follows time.
for (const e of [...AUDIT_EVENTS].reverse()) {
  lines.push(
    `insert into public.audit_events (id, actor_id, actor_role, entity, entity_id, report_id, event, before, after, created_at) values (${q(e.id)}, ${q(e.actorId)}, ${q(e.actorRole)}, ${q(e.entity)}, ${q(e.entityId)}, ${q(e.reportId)}, ${q(e.event)}, ${e.before === null ? "null" : j(e.before)}, ${e.after === null ? "null" : j(e.after)}, ${q(e.createdAt)});`,
  );
}

lines.push("", "commit;", "");

const out = path.resolve(import.meta.dirname, "../supabase/seed.sql");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${AGENTS.length} agents, ${ORDERS.length} orders, ${REPORTS.length} reports, ${AUDIT_EVENTS.length} audit events`);
